f.line3((0, 0, 0), tuple(2.2 * c for c in lam), c=GRY, w=2.5, d="8,4")
f.arrow3((0, 0, 0), r, c=INK, w=2.5); f.arrow3(r, tip, c=RED, w=3)
f.dot3((0, 0, 0)); f.dot3(r)
f.text3((0, 0, 0), "O", dx=-12, dy=-6)
f.text3(r, "r", dx=-12, dy=-4, i=True, b=True)
f.text3(tip, "F", dx=-12, dy=4, c=RED, i=True, b=True)
f.text3(tuple(2.2 * c for c in lam), "axis λ", dx=10, dy=0, a="start", c=GRY)
f.text_px(24, 358, "r = (2, 1, 3) m,  F = (10, −20, 5) kN (reduced scale)", a="start", sz=13)
f.text_px(24, 378, "λ = (i + 2j + 2k)/3", a="start", c=GRY, sz=13)
f.save("p2-6-axis-moment-3d")
