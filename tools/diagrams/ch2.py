from figlib import *
import math

# ---- Example 2.1: moment of an inclined force
f = Fig(560, 330, sc=60, ox=110, oy=275)
f.line(0, 0, 2, 3, c=GRY, w=1.5, d="5,4")
f.dot(0, 0); f.text(0, 0, "O", dx=-14, dy=16)
f.dot(2, 3)
tip = (2 + 0.84, 3 - 1.12)
f.arrow(2, 3, 2.84, 3, c="#e59a92", w=2, d="5,3"); f.arrow(2.84, 3, *tip, c="#e59a92", w=2, d="5,3")
f.arrow(2, 3, *tip, c=RED, w=3)
f.text(2.84, 3, "300 N", dy=-8, c=RED, sz=13); f.text(*tip, "400 N", dx=10, dy=-24, a="start", c=RED, sz=13) if False else f.text(2.84, 2.45, "400 N", dx=10, a="start", c=RED, sz=13)
f.text(*tip, "F = 500 N", dx=8, dy=20, a="start", c=RED, b=True)
f.dim(0, 0, 2, 0, "2 m", off=30); f.dim(0, 0, 0, 3, "3 m", off=-30)
f.moment(0, 0, 34, 150, 30, c=BLUE)
f.text(0, 0, "M_{O} = 1700 N·m (clockwise)", dx=70, dy=-14, a="start", c=BLUE, sz=13)
f.text(1.0, 1.5, "r", dx=-14, dy=0, c=GRY, i=True)
f.save("ex2-1-moment-2d")

# ---- Example 2.2: resultant on a beam
f = Fig(560, 470, sc=60, ox=70, oy=440)
def beam(y):
    f.line(0, y, 6, y, c=INK, w=6)
yt, yb = 4.4, 0.6
f.text_px(20, 24, "Given system", a="start", c=GRY, sz=13)
beam(yt)
f.arrow(1, yt + 0.8, 1, yt, c=RED); f.text(1, yt + 0.8, "200 N", dy=-8, c=RED)
f.arrow(4, yt + 1.2, 4, yt, c=RED); f.text(4, yt + 1.2, "300 N", dy=-8, c=RED)
f.arrow(6, yt - 0.4, 6, yt, c=RED); f.text(6, yt - 0.4, "100 N", dx=10, dy=14, a="start", c=RED)
f.text(0, yt, "A", dx=-14, dy=5); f.text(6, yt, "B", dx=14, dy=-6)
f.dim(0, yt, 1, yt, "1 m", off=24); f.dim(1, yt, 4, yt, "3 m", off=24); f.dim(4, yt, 6, yt, "2 m", off=24)
f.text_px(20, 270, "Equivalent single force", a="start", c=GRY, sz=13)
beam(yb)
f.arrow(2, yb + 1.6, 2, yb, c=GRN, w=3); f.text(2, yb + 1.6, "R = 400 N", dy=-8, c=GRN, b=True)
f.text(0, yb, "A", dx=-14, dy=5); f.text(6, yb, "B", dx=14, dy=-6)
f.dim(0, yb, 2, yb, "x = 2 m", off=24)
f.save("ex2-2-resultant-beam")

# ---- Example 2.3: 3D force along AB
f = Fig3(600, 440, sc=36, ox=210, oy=340)
f.axes3((5, 7.5, 5.5))
A = (1, 0, 2); B = (4, 6, 4)
f.arrow3((0, 0, 0), A, c=GRY, w=1.8, d="5,3")
f.arrow3(A, B, c=RED, w=3.2)
f.dot3((0, 0, 0)); f.dot3(A); f.dot3(B)
f.text3((0, 0, 0), "O", dx=-14, dy=16)
f.text3(A, "A(1, 0, 2)", dx=-10, dy=-8, a="end")
f.text3(B, "B(4, 6, 4)", dx=10, dy=-6, a="start")
f.text3(tuple((a + b) / 2 for a, b in zip(A, B)), "F = 700 N", dx=-8, dy=-12, a="end", c=RED, b=True)
f.text3(tuple(a / 2 for a in A), "r", dx=14, dy=8, c=GRY, i=True)
f.arrow3((0, 0, 0), (-2.4 * 1.0, 0.8, 1.2), c=GRN, w=2.5)
f.text3((-2.4, 0.8, 1.2), "M_{O} (not to scale)", dx=12, dy=22, a="start", c=GRN, sz=12)
f.save("ex2-3-force-3d")

